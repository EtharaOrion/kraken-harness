    """Tests for the keep_major_minor lambda inside get_version."""

    # We test the lambda's behavior indirectly through get_version, but also
    # recreate it for direct unit testing.
    keep_major_minor = staticmethod(lambda x, sep: ".".join(x.strip().split(sep)[:2]))

