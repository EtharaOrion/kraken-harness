# ── Auto-generated fallback paths ────────────────────────────────────────────


class TestAutoGeneratedPaths:
    """Tests for the auto-generated fallback paths when repo not in MAP_REPO_TO_VERSION_PATHS."""

    @pytest.mark.parametrize(
        "repo, expected_repo_name",
        [
            ("unknown-org/my-package", "my_package"),
            ("org/MyPackage", "mypackage"),
            ("org/some_lib", "some_lib"),
            ("org/A-B-C-D", "a_b_c_d"),
            ("deep/nested-repo-name", "nested_repo_name"),
            ("org/x", "x"),
            ("org/UPPER-CASE", "upper_case"),
            ("org/already_underscore", "already_underscore"),
            ("org/mix-of_both", "mix_of_both"),
            ("org/123-pkg", "123_pkg"),
        ],
        ids=[
            "hyphen_to_underscore",
            "uppercase_to_lower",
            "already_underscore",
            "multi_hyphen",
            "org_prefix_stripped",
            "single_char",
            "all_upper_hyphen",
            "no_change_needed",
            "mixed_separator",
            "numeric_prefix",
        ],
    )
    def test_repo_name_derivation(self, repo, expected_repo_name):
        """Repo name derived correctly: split('/'), take last, lower, replace('-','_')."""
        derived = repo.split("/")[-1].lower().replace("-", "_")
        assert derived == expected_repo_name

    @pytest.mark.parametrize(
        "repo",
        [
            "unknown-org/my-package",
            "totally-new/repo-name",
            "org/something-new",
        ],
        ids=["unknown_hyphen", "totally_new", "something_new"],
    )
    def test_fallback_paths_count(self, repo):
        """Auto-generated fallback produces exactly 7 paths."""
        assert repo not in MAP_REPO_TO_VERSION_PATHS
        repo_name = repo.split("/")[-1].lower().replace("-", "_")
        paths = [
            f"{repo_name}/__init__.py",
            f"{repo_name}/_version.py",
            f"{repo_name}/version.py",
            f"src/{repo_name}/__init__.py",
            f"src/{repo_name}/_version.py",
            "setup.cfg",
            "pyproject.toml",
        ]
        assert len(paths) == 7

    @pytest.mark.parametrize(
        "repo, idx, expected_suffix",
        [
            ("org/my-lib", 0, "my_lib/__init__.py"),
            ("org/my-lib", 1, "my_lib/_version.py"),
            ("org/my-lib", 2, "my_lib/version.py"),
            ("org/my-lib", 3, "src/my_lib/__init__.py"),
            ("org/my-lib", 4, "src/my_lib/_version.py"),
            ("org/my-lib", 5, "setup.cfg"),
            ("org/my-lib", 6, "pyproject.toml"),
        ],
        ids=[
            "init_py",
            "underscore_version",
            "version_py",
            "src_init",
            "src_version",
            "setup_cfg",
            "pyproject_toml",
        ],
    )
    def test_fallback_path_content(self, repo, idx, expected_suffix):
        """Each fallback path has correct format."""
        repo_name = repo.split("/")[-1].lower().replace("-", "_")
        paths = [
            f"{repo_name}/__init__.py",
            f"{repo_name}/_version.py",
            f"{repo_name}/version.py",
            f"src/{repo_name}/__init__.py",
            f"src/{repo_name}/_version.py",
            "setup.cfg",
            "pyproject.toml",
        ]
        assert paths[idx] == expected_suffix


