# ── Helpers ──────────────────────────────────────────────────────────────────


def _make_instance(**overrides):
    """Create a minimal instance dict for get_version()."""
    base = {
        "repo": "scikit-learn/scikit-learn",
        "base_commit": "abc123def456",
        "instance_id": "test__1",
    }
    base.update(overrides)
    return base


