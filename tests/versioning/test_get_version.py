            ("1, 2, 3", ",", "1. 2"),
            ("1,2,3", ",", "1.2"),
            ("1,2", ",", "1.2"),
            ("1,", ",", "1."),
            ("  1.2.3  ", ".", "1.2"),
            ("1.2.3rc1", ".", "1.2"),
            ("1.2.3.dev0", ".", "1.2"),
            ("1.2.3a1", ".", "1.2"),
            ("1.2.3b2", ".", "1.2"),
            ("v1.2.3", ".", "v1.2"),
            ("1.2.3.4.5.6", ".", "1.2"),
