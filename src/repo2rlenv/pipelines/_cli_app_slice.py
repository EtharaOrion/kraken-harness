def _project_endpoints_json(text: str, keep_services: frozenset[str]) -> str:
    """Filter endpoints.json's ``partitions[].services`` map to keep only listed services.

    The endpoints.json v3 schema has a top-level ``partitions`` list; each entry
    has a ``services`` dict keyed by service name (``s3``, ``dynamodb``, ...).
    We drop every service not in ``keep_services`` while preserving the outer
    structure (partition metadata, regions, defaults) — botocore's endpoint
    resolver stays functional for kept services and never touches removed ones.
    """
    data = json.loads(text)
    partitions = data.get("partitions") or []
    for partition in partitions:
        services = partition.get("services")
        if isinstance(services, dict):
            partition["services"] = {
                name: cfg for name, cfg in services.items() if name in keep_services
            }
    return json.dumps(data, indent=2, separators=(",", ": "))


def _project_partitions_json(text: str, keep_services: frozenset[str]) -> str:
    """Filter partitions.json.

    partitions.json is a small (~267 lines) file mirroring the newer endpoints.json
    v3 schema. We apply the same ``services`` projection defensively; if the file
    schema does not contain per-service data, the unchanged serialization is
    returned.
    """
    data = json.loads(text)
    partitions = data.get("partitions") or []
    changed = False
    for partition in partitions:
        services = partition.get("services")
        if isinstance(services, dict):
            partition["services"] = {
                name: cfg for name, cfg in services.items() if name in keep_services
            }
            changed = True
    if not changed:
        return text
    return json.dumps(data, indent=2, separators=(",", ": "))


