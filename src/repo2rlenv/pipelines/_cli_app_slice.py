"""Call-graph closure slicer for the cli_app golden oracle.

Replaces the LLM ``_synthesise_oracle`` with a deterministic, byte-for-byte copy
of the real upstream aws-cli source for the task's service, shipped VERBATIM,
plus a tiny GENERATED bootstrap so it runs small.

Design (validated end-to-end against MinIO + the aws-cli v2.28.23 source):

  * The gold = the **static-import closure** of the real code reachable from a
    fixed set of roots — ``clidriver.py``, ``__init__.py``, ``__main__.py``, and
    a GENERATED minimal ``handlers.py``. For the ``s3`` service the roots also
    include the whole ``customizations/s3`` subpackage; for ``dynamodb`` (and
    other model-generated services) they do not — DDB has no customization
    module, its verbs are built at runtime from the botocore service model. The
    closure follows ``import`` / ``from ... import`` edges WITHIN the awscli
    tree, resolving the alias ``botocore.*`` -> ``awscli/botocore/*`` and
    ``s3transfer.*`` -> ``awscli/s3transfer/*`` (the same alias
    ``awscli/__init__.py``'s ``TopLevelImportAliasFinder`` installs at runtime),
    and STOPS at external pip packages (the pyproject deps) + stdlib.
  * The GENERATED ``handlers.py`` keeps the same ``awscli_initialize`` signature
    but registers ONLY the GLOBAL handlers (arg parsing, output, errors,
    pagination, skeleton, waiters, ...) plus the service-specific plugin needed
    by the task (s3 plugin for s3; nothing extra for dynamodb). It DROPS every
    OTHER service-specific customization (ec2/rds/ecr/emr/eks/...). Because the
    generated handlers never imports the dropped customizations, the closure
    never pulls them in — that is what keeps the slice small AND avoids the
    KeyError a service customization raises when its service data is pruned.
  * Every awscli file the closure reaches is emitted VERBATIM (byte-for-byte),
    plus the botocore service **data** the reached code loads at runtime — the
    service model dirs for the task (``s3`` + ``sts`` for s3; ``dynamodb`` +
    ``sts`` for dynamodb) and the top-level ``endpoints.json`` /
    ``partitions.json`` — plus awscli's own ``data/`` (``cli.json`` /
    ``metadata.json``). Service models for everything else are dropped.
  * ``submission/aws`` is the ONLY generated file: an executable ``#!/bin/sh``
    shim that bootstraps the slice INLINE (``python3 -c`` prepends
    ``/workspace/submission`` to ``sys.path``, sets ``argv[0]="aws"``,
    dispatches to ``awscli.clidriver.main``). There is NO ``submission/main.py``.
    NO ``_botocore_compat`` shim, NO exclude-list, NO pip botocore — botocore is
    VENDORED.
  * The gold patch is a ``\\n``-only new-file diff (NOT ``str.splitlines()``,
    which corrupts files with form-feed / U+2028). Every emitted file is
    asserted to reconstruct byte-identically; a provenance sha256 manifest of
    the verbatim files is returned.
"""

